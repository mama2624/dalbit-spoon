  function lunarPair(y, m, d, cal, leap) {
    var S = window.SAJU;
    if (!S) return { solar: { y: y, m: m, d: d }, lunar: null, err: null };
    if (cal === "lunar") {
      var s = S.lunarToSolar(y, m, d, !!leap);
      if (!s) return { solar: null, lunar: null, err: "그 음력 날짜를 찾지 못했어요. 윤달 여부와 월·일을 확인해 주세요." };
      return { solar: s, lunar: { y: y, m: m, d: d, leap: !!leap }, err: null };
    }
    var l = S.solarToLunar(y, m, d);
    return { solar: { y: y, m: m, d: d }, lunar: l || null, err: null };
  }

  function build(st) {
    var lp = lunarPair(st.y, st.m, st.d, st.cal, st.leap);
    if (lp.err) return { err: lp.err };
    var sol = lp.solar;

    var seed = sol.y + "-" + pad2(sol.m) + "-" + pad2(sol.d);
    var n = (hashStr(seed) % 144) + 1;
    var a = Math.floor((n - 1) / 12), b = (n - 1) % 12, c = (a + b) % 12;

    var F = FLOW[a], M = MOD[b];

    /* 월별 기운 */
    var months = [], i, sc;
    for (i = 0; i < 12; i++) {
      sc = 52 + Math.round(F.m[i] * 1.5);
      if (M.good.indexOf(i + 1) >= 0) sc += 9;
      if (M.care.indexOf(i + 1) >= 0) sc -= 9;
      sc += (hashStr(n + ":" + (i + 1)) % 9) - 4;
      if (sc > 97) sc = 97;
      if (sc < 15) sc = 15;
      months.push(sc);
    }
    var order = [];
    for (i = 0; i < 12; i++) order.push({ m: i + 1, s: months[i] });
    var byScore = order.slice().sort(function (x, y2) { return y2.s - x.s || x.m - y2.m; });
    /* 가장 높은 달·가장 낮은 달에서 6점 안쪽의 달만 골라 강조합니다(최대 3·2개) */
    var top = byScore[0].s, low = byScore[11].s;
    var best = byScore.filter(function (o) { return o.s >= top - 6; }).slice(0, 3);
    var care = byScore.filter(function (o) { return o.s <= low + 6; }).slice(-2);
    best.sort(function (x, y2) { return x.m - y2.m; });
    care.sort(function (x, y2) { return x.m - y2.m; });

    /* 행운 숫자 3개 (1~45) */
    var rng = makeRng(hashStr(seed + "|tj"));
    var pool = [], nums = [];
    for (i = 1; i <= 45; i++) pool.push(i);
    for (i = 0; i < 3; i++) {
      var k = i + Math.floor(rng() * (45 - i)), t = pool[i];
      pool[i] = pool[k]; pool[k] = t;
      nums.push(pool[i]);
    }
    nums.sort(function (x, y2) { return x - y2; });

    var zodiac = ZH_ANIMAL[(sol.y - 4) % 12];

    return {
      err: null,
      n: n, a: a, b: b, c: c,
      F: F, M: M, h: HAGWE[c],
      seed: seed, sol: sol, lunar: lp.lunar,
      cal: st.cal, leap: !!st.leap, gender: st.gender || "",
      inDate: { y: st.y, m: st.m, d: st.d },
      months: months, best: best, care: care,
      nums: nums, zodiac: zodiac
    };
  }

