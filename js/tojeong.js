  var ST = { cal: "solar", leap: false, y: 1990, m: 1, d: 1, gender: "" };

  function days() {
    var y = +$("tjY").value, m = +$("tjM").value, sel = $("tjD");
    var max = new Date(y, m, 0).getDate();
    var cur = +sel.value || 1;
    if (cur > max) cur = max;
    var html = "";
    for (var d = 1; d <= max; d++) html += "<option" + (d === cur ? " selected" : "") + ">" + d + "</option>";
    sel.innerHTML = html;
  }

  function init() {
    if (!$("paneTojeong")) return;
    var ySel = $("tjY"), mSel = $("tjM");
    if (!ySel || !mSel) return;

    var yo = "";
    for (var y = 2015; y >= 1930; y--) yo += "<option" + (y === 1990 ? " selected" : "") + ">" + y + "</option>";
    ySel.innerHTML = yo;

    var mo = "";
    for (var m = 1; m <= 12; m++) mo += "<option" + (m === 1 ? " selected" : "") + ">" + m + "</option>";
    mSel.innerHTML = mo;
    days();
    ySel.addEventListener("change", days);
    mSel.addEventListener("change", days);

    /* 양력 / 음력 */
    var cals = document.querySelectorAll('input[name="tjCal"]');
    for (var i = 0; i < cals.length; i++) {
      cals[i].addEventListener("change", function () {
        ST.cal = this.value;
        var lw = $("tjLeapWrap");
        if (lw) lw.hidden = (ST.cal !== "lunar");
        if (ST.cal !== "lunar") { var lc = $("tjLeap"); if (lc) lc.checked = false; ST.leap = false; }
        $("tjMsg").textContent = "";
      });
    }
    var leap = $("tjLeap");
    if (leap) leap.addEventListener("change", function () { ST.leap = this.checked; });

    /* 성별 (선택) */
    var gs = document.querySelectorAll('input[name="tjGender"]');
    for (var g = 0; g < gs.length; g++) {
      gs[g].addEventListener("change", function () { ST.gender = this.value; });
    }

    $("tjBtn").addEventListener("click", function () {
      ST.y = +$("tjY").value;
      ST.m = +$("tjM").value;
      ST.d = +$("tjD").value;
      var msg = $("tjMsg");
      if (msg) msg.textContent = "";
      var r = build(ST);
      if (r.err) {
        if (msg) msg.textContent = r.err;
        $("tjResult").innerHTML = "";
        return;
      }
      render(r);
    });
  }

